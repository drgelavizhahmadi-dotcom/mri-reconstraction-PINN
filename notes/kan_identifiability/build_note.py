def f2() -> None:
    npz = FIG / "data" / "d2_layer1_curves.npz"
    if not npz.exists():
        print("  SKIP F2: figures/data/d2_layer1_curves.npz missing")
        return
    z = np.load(npz)
    seeds = [int(s) for s in z["seeds"]]
    r2 = {s: float(r) for s, r in zip(seeds, z["r2"])}
    wc = [s for s in seeds if r2[s] > R2_THRESHOLD]
    ref = wc[0]
    fig, ax = plt.subplots(2, 2, figsize=(12, 8))
    for s in seeds:
        ok = s in wc
        st = dict(alpha=0.85, lw=1.5) if ok else dict(alpha=0.3, lw=0.9, ls=":")
        ax[0, 0].plot(z["x1"], z[f"s{s}_x1"], **st)
        ax[1, 0].plot(z["x2"], z[f"s{s}_x2"], **st)
    for s in wc:
        fit = raw_and_quotiented(z[f"s{ref}_x1"], z[f"s{s}_x1"])  # ref ~ a*s + b, from x1 ONLY
        a, b = fit["a"], fit["b"]
        ax[0, 1].plot(z["x1"], a * z[f"s{s}_x1"] + b, alpha=0.85, lw=1.5)
        ax[1, 1].plot(z["x2"], a * z[f"s{s}_x2"] + b, alpha=0.85, lw=1.5)
    ax[0, 0].set_title("layer1 x1-edge, raw (dotted = not well-converged)")
    ax[0, 1].set_title(f"x1-edge after per-seed affine align to seed {ref}")
    ax[1, 0].set_title("layer1 x2-edge, raw")
    ax[1, 1].set_title("x2-edge under the SAME transform fitted on x1")
    for a_ in ax.ravel():
        a_.grid(alpha=0.25)
    fig.suptitle("F2. Additive d≥2: one shared affine map aligns BOTH edges of the node")
    fig.tight_layout()
    fig.savefig(FIG / "F2_d2_edges_shared_affine.png", dpi=130)
    plt.close(fig)
    print("  wrote figures/F2_d2_edges_shared_affine.png")



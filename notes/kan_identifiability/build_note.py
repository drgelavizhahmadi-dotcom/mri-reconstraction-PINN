def check_draft() -> int:
    """draft.md inlines the generated tables so it reads standalone. This verifies no
    inlined row has drifted from tables/. Run after regenerating. T7 is inlined only as
    a summary (60 rows), so its per-seed rows are exempt."""
    import re
    draft = (OUT / "draft.md").read_text()

    def rows(txt: str) -> list[tuple]:
        out = []
        for ln in txt.splitlines():
            ln = ln.strip()
            if ln.startswith("|") and not re.match(r"^\|[\s\-:|]+\|$", ln):
                out.append(tuple(c.strip() for c in ln.strip("|").split("|")))
        return out

    draft_rows = set(rows(draft))
    bad = 0
    for f in sorted(TAB.glob("T*.md")):
        if f.name.startswith("T7"):
            continue
        for r in rows(f.read_text()):
            if len(r) >= 2 and r not in draft_rows:
                print(f"  DRIFT [{f.name}]: {r}")
                bad += 1
    print("  draft.md matches tables/" if bad == 0 else f"  {bad} row(s) drifted -- re-inline them")
    return bad



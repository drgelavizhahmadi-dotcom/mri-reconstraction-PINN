R2_THRESHOLD = 0.999


def load(name: str) -> dict:
    return json.loads((RES / f"{name}.json").read_text())


def commit_of(name: str) -> str:
    p = RES / f"{name}.json"
    try:
        return subprocess.run(["git", "log", "-1", "--format=%h", "--", str(p)],
                               cwd=REPO, capture_output=True, text=True).stdout.strip() or "UNCOMMITTED"
    except Exception:
        return "UNKNOWN"


def write_table(fname: str, sources: list[str], title: str, lines: list[str]) -> None:
    src = "\n".join(f"<!-- source: experiments/identifiability_gate/results/{s}.json "
                    f"@ commit {commit_of(s)} -->" for s in sources)
    (TAB / fname).write_text(f"<!-- {title} -->\n{src}\n<!-- generated by notes/kan_identifiability/"
                              f"build_note.py -- do not hand-edit -->\n\n" + "\n".join(lines) + "\n")
    print(f"  wrote tables/{fname}")


def md(rows: list[list[str]], header: list[str], align: list[str] | None = None) -> list[str]:
    align = align or ["---"] * len(header)
    return ["| " + " | ".join(header) + " |", "| " + " | ".join(align) + " |"] + \
           ["| " + " | ".join(r) + " |" for r in rows]



def t6() -> None:
    m = load("kan_multiplicative")
    s = m["summary"]
    P, A, PW = [], [], []
    for r in m["pairs"]:
        for e in r["edges"].values():
            if e.get("inconclusive"):
                continue
            P.append(e["p"]); A.append(e["affine_residual_full"]); PW.append(e["power_residual"])
    P, A, PW = np.array(P), np.array(A), np.array(PW)
    dev = np.abs(P - 1.0)
    strat = []
    for lo, hi, lbl in [(0, .15, "[0, 0.15)"), (.15, .5, "[0.15, 0.5)"),
                         (.5, 1., "[0.5, 1.0)"), (1., 1e9, "[1.0, ∞)")]:
        k = (dev >= lo) & (dev < hi)
        if k.sum():
            strat.append([lbl, str(int(k.sum())), f"{A[k].mean():.4f}",
                          f"{PW[k].mean():.4f}", f"{A[k].mean()/PW[k].mean():.1f}×"])
    c1 = [r["edges"]["1"]["c"] for r in m["pairs"] if not r["edges"]["1"].get("inconclusive")]
    p1 = [r["edges"]["1"]["p"] for r in m["pairs"] if not r["edges"]["1"].get("inconclusive")]
    corr_pc = float(np.corrcoef(p1, np.log(np.abs(c1)))[0, 1])

    write_table("T6_multiplicative_power_gauge.md",
                ["kan_multiplicative"],
                "T6. Multiplicative node: power vs affine quotient",
                ["**T6.** Multiplicative node (`MultKAN[2→1→1]`, target `exp(-x1)·sin(pi*x2)`), "
                 "8 well-converged seeds / 28 pairs / 56 edge-fits, 0 inconclusive "
                 "(100% of the domain retained on every pair).", "",
                 "**(a) Overall**", ""] +
                md([["affine quotient (full grid)", f"{s['affine_full_mean']:.4f}"],
                    ["affine quotient (matched domain)", f"{s['affine_matched_domain_mean']:.4f}"],
                    ["power quotient", f"{s['power_mean']:.4f}"],
                    ["power advantage overall", f"{s['affine_full_mean']/s['power_mean']:.1f}×"]],
                   ["quantity", "residual"]) +
                ["", "**(b) Stratified by |p − 1|.** Affine is the `p=1` slice of the power group, so "
                 "pairs that land near `p=1` are affine-stable by construction; the two quotients "
                 "separate only as the exponent leaves that slice. "
                 f"corr(|p−1|, affine residual) = {np.corrcoef(dev, A)[0,1]:+.4f}.", ""] +
                md(strat, ["\\|p − 1\\|", "n edges", "affine residual", "power residual",
                           "power advantage"]) +
                ["", "**(c) Shared exponent (P3)**", ""] +
                md([["within-pair relative \\|p1 − p2\\|", f"{s['p3_within_mean']:.4f} "
                                                        f"({s['p3_within_mean']*100:.2f}%)"],
                    ["across-pair SD of p", f"{s['p_across_std']:.4f}"],
                    ["ratio within / across", f"{s['p3_ratio']:.4f}"],
                    ["observed range of p", f"[{P.min():.3f}, {P.max():.3f}]"]],
                   ["quantity", "value"]) +
                ["", f"**(d) Prefactors.** `corr(p, log|c1|) = {corr_pc:+.4f}` — the fitted prefactor "
                 f"is largely determined by the exponent, not an independent coordinate "
                 f"(see methods: the pre-registered torus test is not identifiable as posed)."])


